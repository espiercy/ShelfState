export const WORKER_RELEASE_SOURCES = Object.freeze([
  "/service-worker.js",
  "/src/pwa/service-worker-policy.js",
]);

export function normalizeTextContent(value) {
  return value.replace(/\r\n?|\r/g, "\n");
}

export function calculateSha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function calculateReleaseSha256(resources, workerSources) {
  return calculateSha256(JSON.stringify({ resources, workerSources }));
}

async function hashRepositoryFile(rootDirectory, definition) {
  const fileBytes = await readFile(
    path.join(rootDirectory, definition.url.slice(1)),
  );
  const digestInput =
    definition.kind === "text"
      ? normalizeTextContent(fileBytes.toString("utf8"))
      : fileBytes;

  return calculateSha256(digestInput);
}

export async function buildPrecacheManifest(rootDirectory) {
  const resources = [];

  for (const definition of SHELL_RESOURCE_DEFINITIONS) {
    resources.push({
      ...definition,
      sha256: await hashRepositoryFile(rootDirectory, definition),
    });
  }

  const workerSources = [];

  for (const url of WORKER_RELEASE_SOURCES) {
    workerSources.push({
      url,
      sha256: await hashRepositoryFile(rootDirectory, {
        url,
        kind: "text",
      }),
    });
  }

  const releaseSha256 = calculateReleaseSha256(resources, workerSources);

  return {
    cacheName: `shelfstate-shell-${releaseSha256}`,
    resources,
  };
}

export function renderPrecacheManifest(manifest) {
  return [
    "// Generated by scripts/generate-precache-manifest.mjs. Do not edit manually.",
    `export const SHELL_CACHE_NAME = ${JSON.stringify(manifest.cacheName)};`,
    `export const PRECACHE_RESOURCES = Object.freeze(${JSON.stringify(manifest.resources, null, 2)});`,
    "",
  ].join("\n");
}

export async function generatePrecacheManifest(rootDirectory) {
  const manifest = await buildPrecacheManifest(rootDirectory);
  const output = renderPrecacheManifest(manifest);

  await writeFile(
    path.join(rootDirectory, "src/pwa/precache-manifest.js"),
    output,
    "utf8",
  );

  return output;
}

const currentFilePath = fileURLToPath(import.meta.url);
const invokedFilePath = process.argv[1] ? path.resolve(process.argv[1]) : "";

if (pathToFileURL(invokedFilePath).href === pathToFileURL(currentFilePath).href) {
  const rootDirectory = path.resolve(path.dirname(currentFilePath), "..");
  await generatePrecacheManifest(rootDirectory);
}
